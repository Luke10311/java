-- ------------------------------------------------------------
-- 1. case_file 案卷表
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `case_file` (
  `id`          BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
  `case_no`     VARCHAR(32)  NOT NULL DEFAULT ''     COMMENT '卷号（甲字第〇二六卷）',
  `title`       VARCHAR(64)  NOT NULL                COMMENT '案名',
  `tag`         VARCHAR(32)  NOT NULL DEFAULT ''     COMMENT '题签（疑涉妖异/关联三案…）',
  `description` VARCHAR(512) NOT NULL DEFAULT ''     COMMENT '案情摘要（卡片上的一段话）',
  `place`       VARCHAR(64)  NOT NULL DEFAULT ''     COMMENT '案发地',
  `status`      VARCHAR(16)  NOT NULL DEFAULT '缉查中' COMMENT '状态（缉查中/待复核/已封卷）',
  `reward`      VARCHAR(32)  NOT NULL DEFAULT ''     COMMENT '悬赏文案',
  `image`       VARCHAR(255) NOT NULL DEFAULT ''     COMMENT '案卷插图地址',
  `summary`     TEXT         NULL                    COMMENT '完整卷宗（详情页正文）',
  `is_active`   TINYINT      NOT NULL DEFAULT 1      COMMENT '是否启用（1启用 0停用）',
  `created_at`  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `updated_at`  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  KEY `idx_status` (`status`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_general_ci COMMENT = '案卷表';

-- ------------------------------------------------------------
-- 2. site_config 站点配置表（系统设置里可改）
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS `site_config` (
  `config_key`   VARCHAR(64)  NOT NULL COMMENT '配置键',
  `config_value` TEXT         NULL     COMMENT '配置值',
  `label`        VARCHAR(64)  NOT NULL DEFAULT '' COMMENT '中文名（后台展示用）',
  `remark`       VARCHAR(255) NOT NULL DEFAULT '' COMMENT '说明',
  `updated_at`   DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`config_key`)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_general_ci COMMENT = '站点配置表';

